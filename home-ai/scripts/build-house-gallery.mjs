// The House view gallery: four photoreal AI renders of this home (Higgsfield, GPT Image 2.5)
// plus thumbnails for every choice, written as web/house-stills/gallery.js with the pictures
// inlined (the one-file demo carries them; the home server serves the same module).
// Sources: web/house-stills/renders/<id>.webp, <id>-thumb.webp and renders.json, which holds
// each render's name, mood, edge color and where each room's button sits (fractions of the
// picture). Edit renders.json to move a button, then: npm run build:house-gallery && build:demo
import { readFileSync, writeFileSync } from "node:fs";

const dir = "web/house-stills/renders";
const spec = JSON.parse(readFileSync(`${dir}/renders.json`, "utf8"));
const uri = (f) => `data:image/webp;base64,${readFileSync(`${dir}/${f}`).toString("base64")}`;
const size = (f) => { const b = readFileSync(`${dir}/${f}`), i = b.indexOf("VP8"); // width and height from the WebP header
  if (b.toString("latin1", i, i + 4) === "VP8 ") return [b.readUInt16LE(i + 14) & 0x3fff, b.readUInt16LE(i + 16) & 0x3fff];
  if (b.toString("latin1", i, i + 4) === "VP8L") { const v = b.readUInt32LE(i + 9); return [(v & 0x3fff) + 1, ((v >> 14) & 0x3fff) + 1]; }
  return [1 + b.readUIntLE(i + 12, 3), 1 + b.readUIntLE(i + 15, 3)]; };
const renders = Object.entries(spec).map(([id, r]) => { const [w, h] = size(`${id}.webp`); return { id, ...r, w, h, src: uri(`${id}.webp`), thumb: uri(`${id}-thumb.webp`) }; });
const thumbs = { cgi: uri("cgi-thumb.webp"), hologram: uri("hologram-thumb.webp") };
writeFileSync("web/house-stills/gallery.js", `// Generated by npm run build:house-gallery from web/house-stills/renders/ (do not edit by hand).
// The photoreal renders show this home only: the panel uses them when the home matches the one
// they were made for (HOUSE_STILLS.sig), and otherwise falls back to the live 3D view.
export const HOUSE_RENDERS = ${JSON.stringify(renders)};
export const HOUSE_THUMBS = ${JSON.stringify(thumbs)};
`);
console.log(`web/house-stills/gallery.js: ${renders.map((r) => `${r.id} ${r.w}x${r.h}`).join(", ")}`);
